export function buildJobMatchPrompt(input: {
  projectName: string;
  jobPosting: string;
  logsFormatted: string;
}) {
  return `아래는 지원하려는 채용공고와, "${input.projectName}" 활동 중 남긴 기록입니다.

[채용공고]
${input.jobPosting}

[활동 기록]
${input.logsFormatted}

이 채용공고의 요구 역량·우대사항에 맞춰, 기록에 있는 내용 중 이 공고와 가장 관련성 높은 경험을 우선적으로 배치하고 강조한 포트폴리오를 STAR(상황-과제-행동-결과) 형식으로 작성해주세요.

규칙:
- 기록에 없는 사실·수치는 절대 만들어내지 마세요.
- 채용공고에서 요구하는 키워드·기술과 실제 기록을 연결지어 서술하세요.
- 공고와 관련성이 낮은 활동은 간결하게 줄이거나 생략하세요.
- 아래 마크다운 형식과 순서를 그대로 지키세요.

# ${input.projectName} 포트폴리오 (공고 맞춤)

## 이 공고와의 적합도 요약
공고의 핵심 요구사항 2~3개를 뽑아, 기록의 어떤 경험이 그것과 연결되는지 1~2문장씩 서술하세요. 관련 경험이 기록에 없는 요구사항은 지어내지 말고 "관련 경험 부족"이라고 솔직하게 표시하세요.

## 주요 활동
기록을 공고와의 관련도가 높은 순으로 2~3개 활동으로 묶어 정리하세요. 각 활동은 아래 STAR 구조로, 각 항목 2~3문장 이상 구체적으로 작성하세요.
### 활동 제목
- 상황(Situation):
- 과제(Task):
- 행동(Action):
- 결과(Result):

## 핵심 성과 요약
4~6개 불릿, 가능하면 공고의 표현/키워드와 연결지어 작성하고 근거 날짜를 괄호로 표시하세요.

한국어로 작성하고, <br> 등 HTML 태그는 쓰지 마세요. 전체 2000자 내외로 작성하세요.`;
}
